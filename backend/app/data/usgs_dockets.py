def _build_records(raw: list, state: str) -> list[dict]:
    out = []
    for r in raw:
        county, docket, agency, prop, commodity, size_mb = r
        out.append({
            "state": state,
            "county": county,
            "docket": docket,
            "agency": agency,
            "property": prop,
            "commodity": commodity,
            "size_mb": size_mb,
            "land_hint": land_hint(prop),
        })
    return out


UTAH_RECORDS = _build_records(_UTAH_RAW, "Utah")
NEVADA_RECORDS = _build_records(_NEVADA_RAW, "Nevada")
ALL_RECORDS = UTAH_RECORDS + NEVADA_RECORDS


def build_dataset_context() -> str:
    """Return a compact CSV block of all records for inclusion in AI system context."""
    lines = ["county,state,docket,agency,property,commodity,size_mb,land_hint"]
    for r in ALL_RECORDS:
        size = str(r["size_mb"]) if r["size_mb"] > 0 else "<1"
        lines.append(
            f'{r["county"]},{r["state"]},{r["docket"]},{r["agency"]},'
            f'"{r["property"]}","{r["commodity"]}",{size},{r["land_hint"]}'
        )
    return "\n".join(lines)


def build_county_summaries() -> str:
    """Return a per-county summary string."""
    from collections import defaultdict

    counties: dict[tuple, dict] = defaultdict(lambda: {
        "dockets": 0, "total_mb": 0, "commodities": defaultdict(int),
        "agencies": defaultdict(int), "land": defaultdict(int),
    })
    for r in ALL_RECORDS:
        key = (r["state"], r["county"])
        c = counties[key]
        c["dockets"] += 1
        c["total_mb"] += r["size_mb"]
        for comm in r["commodity"].split(","):
            c["commodities"][comm.strip()] += 1
        c["agencies"][r["agency"]] += 1
        c["land"][r["land_hint"]] += 1

    CRITICAL = {"uranium", "cobalt", "tungsten", "rare earths", "lithium", "vanadium"}

    lines = ["STATE|COUNTY|DOCKETS|TOTAL_MB|TOP_COMMODITY|CRITICAL|BLM%|STATE%|PRIVATE%|AGENCIES"]
    for (state, county), c in sorted(counties.items(), key=lambda x: -x[1]["total_mb"]):
        top_comm = max(c["commodities"], key=c["commodities"].get) if c["commodities"] else "—"
        has_critical = any(cm.lower() in CRITICAL for cm in c["commodities"])
        n = c["dockets"]
        blm_pct = round(c["land"]["BLM"] / n * 100)
        state_pct = round(c["land"]["State"] / n * 100)
        priv_pct = round(c["land"]["Private"] / n * 100)
        agencies = ",".join(f"{a}:{v}" for a, v in sorted(c["agencies"].items()))
        lines.append(
            f"{state}|{county}|{n}|{c['total_mb']}|{top_comm}|"
            f"{'YES' if has_critical else 'no'}|{blm_pct}%|{state_pct}%|{priv_pct}%|{agencies}"
        )
    return "\n".join(lines)
